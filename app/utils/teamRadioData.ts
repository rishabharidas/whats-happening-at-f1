interface OpenF1RawRadio {
  date: string;
  driver_number: number;
  meeting_key: number;
  recording_url: string;
  session_key: number;
}

interface OpenF1DriverInfo {
  driver_number: number;
  full_name?: string;
  name_acronym?: string;
  team_name?: string;
  team_colour?: string;
  headshot_url?: string;
}

export async function fetchTeamRadioData(): Promise<RadioTransmission[]> {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 2500);

    const [radioRes, driversRes] = await Promise.all([
      fetch("https://api.openf1.org/v1/team_radio?session_key=latest", {
        signal: controller.signal,
        next: { revalidate: 60 },
      }).catch(() => null),
      fetch("https://api.openf1.org/v1/drivers?session_key=latest", {
        signal: controller.signal,
        next: { revalidate: 300 },
      }).catch(() => null),
    ]);

    clearTimeout(timeoutId);

    const driversMap: Record<number, OpenF1DriverInfo> = {};
    if (driversRes && driversRes.ok) {
      const driversJson = (await driversRes.json()) as OpenF1DriverInfo[];
      if (Array.isArray(driversJson)) {
        for (const d of driversJson) {
          if (typeof d.driver_number === "number") {
            driversMap[d.driver_number] = d;
          }
        }
      }
    }

    if (radioRes && radioRes.ok) {
      const radioJson = (await radioRes.json()) as OpenF1RawRadio[];
      if (Array.isArray(radioJson) && radioJson.length > 0) {
        // Take up to 10 latest live transmissions from OpenF1
        const liveItems: RadioTransmission[] = radioJson
          .slice(-10)
          .reverse()
          .map((item, idx) => {
            const driver = driversMap[item.driver_number];
            const num = item.driver_number;
            const driverName = driver?.full_name || `Driver #${num}`;
            const driverCode =
              driver?.name_acronym ||
              (driver?.full_name ? driver.full_name.substring(0, 3).toUpperCase() : `#${num}`);
            const team = driver?.team_name || "Formula 1 Team";
            const teamHex = driver?.team_colour
              ? driver.team_colour.startsWith("#")
                ? driver.team_colour
                : `#${driver.team_colour}`
              : "#E80020";

            return {
              id: `live-openf1-${item.session_key}-${item.driver_number}-${idx}`,
              driverNumber: num,
              driverName,
              driverCode,
              teamName: team,
              teamColour: teamHex,
              headshotUrl: driver?.headshot_url,
              speaker: "DRIVER",
              speakerName: driverName,
              sessionName: `Live Session Feed #${item.session_key}`,
              date: item.date,
              category: "STRATEGY",
              transcript: `Live pit-wall telemetry radio transmission recorded from driver #${num} during session ${item.session_key}.`,
              recordingUrl: item.recording_url,
              durationSeconds: 5,
              featured: false,
              isLiveFeed: true,
            };
          });

        return [...liveItems, ...CURATED_RADIO_TRANSMISSIONS];
      }
    }
  } catch {
    // Graceful fallback to curated data
  }

  return CURATED_RADIO_TRANSMISSIONS;
}

